-- Kim Flora: password-only guest accounts. Run AFTER initial schema.
-- Do not put passwords or pepper in GitHub, HTML, or SQL.
create schema if not exists private;
create table if not exists private.kf_guest_credentials (
  id uuid primary key default gen_random_uuid(),
  label text not null check (length(label) between 1 and 120),
  lookup_digest text not null unique,
  password_hash text not null,
  password_salt text not null,
  created_at timestamptz not null default now(),
  revoked_at timestamptz
);
create table if not exists private.kf_guest_sessions (
  token_digest text primary key,
  guest_id uuid not null references private.kf_guest_credentials(id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);
create index if not exists kf_guest_sessions_guest_idx on private.kf_guest_sessions(guest_id);
create index if not exists kf_guest_sessions_expires_idx on private.kf_guest_sessions(expires_at);
create table if not exists private.kf_guest_login_attempts (
  id bigint generated by default as identity primary key,
  client_digest text not null,
  created_at timestamptz not null default now()
);
create index if not exists kf_guest_attempts_client_idx on private.kf_guest_login_attempts(client_digest,created_at desc);
alter table private.kf_guest_credentials enable row level security;
alter table private.kf_guest_sessions enable row level security;
alter table private.kf_guest_login_attempts enable row level security;
revoke all on schema private from public, anon, authenticated;
revoke all on private.kf_guest_credentials from public, anon, authenticated;
revoke all on private.kf_guest_sessions from public, anon, authenticated;
revoke all on private.kf_guest_login_attempts from public, anon, authenticated;
-- Supabase Edge Function using service_role performs credential verification and reads.
-- Revoke SELECT from all non-admin Supabase Auth users on the content table too:
drop policy if exists "kf_public_read" on public.kf_content;
drop policy if exists "kf_authenticated_read" on public.kf_content;
drop policy if exists "kf_admin_content_read" on public.kf_content;
create policy "kf_admin_content_read" on public.kf_content
  for select to authenticated using (public.kf_is_admin());
revoke select on public.kf_content from anon;
grant select on public.kf_content to authenticated;
